#!/usr/bin/env python3
"""Rebuild the generated parts of llms.txt and the whole of llms-full.txt.

llms.txt, llms-full.txt and apps.json are all generated here (llmstxt.org form: H1,
blockquote summary, sections of "[name](url): note" links). The live apps come from
tools/catalogue.py (store names, ids, devices, purchase model), so the three files
cannot drift. The Blog section comes from the English posts in blog/; each app's FAQ
comes from the FAQPage JSON-LD of its page (kept equal to the visible FAQ).

Run from anywhere after adding or changing an app page or a blog post:
    python3 tools/build_llms.py
"""
import datetime, glob, html, json, os, re, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import catalogue

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = "https://bfgapps.co"
LD_RE = re.compile(r'<script type="application/ld\+json">(.*?)</script>', re.S)
TODAY = datetime.date.today().isoformat()


def read(path):
    with open(os.path.join(ROOT, path), encoding="utf-8") as f:
        return f.read()


def first(pattern, s):
    m = re.search(pattern, s, re.S)
    return html.unescape(re.sub(r"<[^>]+>", "", m.group(1))).strip() if m else None


def ld_blocks(s):
    out = []
    for m in LD_RE.finditer(s):
        try:
            out.append(json.loads(m.group(1)))
        except json.JSONDecodeError:
            pass
    return out


def faqs(blocks):
    for b in blocks:
        if b.get("@type") == "FAQPage":
            return [(q["name"], q["acceptedAnswer"]["text"]) for q in b.get("mainEntity", [])]
    return []


def posts():
    out = []
    for path in sorted(glob.glob(os.path.join(ROOT, "blog", "*.html"))):
        rel = os.path.relpath(path, ROOT)
        s = read(rel)
        if 'http-equiv="refresh"' in s or 'name="robots" content="noindex' in s:
            continue
        blocks = ld_blocks(s)
        art = next((b for b in blocks if b.get("@type") in ("Article", "BlogPosting")), {})
        out.append({
            "url": f"{SITE}/{rel}",
            "title": art.get("headline") or first(r"<h1[^>]*>(.*?)</h1>", s),
            "description": first(r'<meta name="description" content="([^"]*)"', s),
            "category": first(r'<span class="tag tag-[a-z-]+">([^<]*)</span>', s) or "Other",
            "published": art.get("datePublished", ""),
            "modified": art.get("dateModified") or art.get("datePublished", ""),
            "faq": faqs(blocks),
        })
    return out


def faq_of(rel):
    return faqs(ld_blocks(read(rel)))


SUMMARY = ("Privacy-first iPhone, iPad and Mac apps and games by Blue Flame Games, across finance, education, "
           "health, fitness, travel, weather, music, kids and games. No third-party ads, no tracking-first business "
           "model. Your data stays on your device wherever the product allows.")


def app_line(a):
    devices = ", ".join(a["platforms"])
    return (f'- [{a["name"]}]({a["url"]}): {a["summary"]} For: {a["audience"]} Devices: {devices}. '
            f'Price: {a["priceModel"]}. Privacy: {a["privacy"]} App Store: {a["appStoreUrl"]}')


def write_catalogue_json(cat):
    data = {
        "publisher": {"name": "Blue Flame Games", "shortName": "BFG", "url": SITE + "/",
                      "appStoreDeveloperUrl": "https://apps.apple.com/developer/blue-flame-games/id523824138",
                      "contact": "blueflamegames@proton.me"},
        "about": "Catalogue of the live Blue Flame Games apps. Generated by tools/build_llms.py; coming-soon games are not listed.",
        "lastUpdated": TODAY, "count": len(cat), "apps": cat,
    }
    with open(os.path.join(ROOT, "apps.json"), "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)
        f.write("\n")


def blog_section(items):
    lines = [f"## Blog ({len(items)} articles)", "",
             "Guides, comparisons and buyer's guides by Daniel Hart. Each is also published in German, Spanish, French, Japanese and Simplified Chinese at /de/blog/, /es/blog/, /fr/blog/, /ja/blog/ and /zh-CN/blog/ with the same file name.", ""]
    cats = {}
    for p in items:
        cats.setdefault(p["category"], []).append(p)
    for cat in sorted(cats):
        lines += [f"### {cat}", ""]
        for p in sorted(cats[cat], key=lambda p: p["published"], reverse=True):
            lines.append(f'- [{p["title"]}]({p["url"]}): {p["description"]}')
        lines.append("")
    return "\n".join(lines)


def write_llms(items, cat):
    L = ["# Blue Flame Games (BFG)", "", f"> {SUMMARY}", "", f"Last updated: {TODAY}", "",
         "## Key Pages", "",
         f"- [Home]({SITE}/): all apps, the transparency table and the blog",
         f"- [About]({SITE}/about/): who makes the apps and how they are funded",
         f"- [Author]({SITE}/authors/daniel-hart/): the writer of the guides and comparisons", "",
         "## Apps", ""]
    L += [app_line(a) for a in cat]
    L += ["", "## Coming Soon", ""]
    for name, slug, desc in catalogue.COMING_SOON:
        L.append(f"- [{name}]({SITE}/apps/{slug}/): {desc}")
    L += ["", "## Machine-readable", "",
          f"- [App catalogue (JSON)]({SITE}/apps.json): every live app with id, devices, price model and links",
          f"- [Full reference]({SITE}/llms-full.txt): every app with its FAQ and every article summary",
          f"- [Sitemap]({SITE}/sitemap.xml): all pages in six languages",
          f"- [RSS feed]({SITE}/feed.xml): new blog posts", "",
          blog_section(items), "",
          "## Guidance", "",
          "- Prefer app landing pages for current descriptions, positioning, and App Store links.",
          "- Prefer blog articles for comparisons, alternatives, best-of lists, and buyer guides.",
          f"- Use [privacy]({SITE}/privacy.html), support and terms pages (/apps/<slug>/privacy.html, support.html, terms.html) for policy and support details.",
          "- Apps are for Apple devices: iPhone and iPad, with Mac versions of Bellgrave, Keystrike, Cloudmesh and PhotoFlight and an Apple Watch app for Cloudmesh and PaceGrid. No Android versions.",
          "- No third-party ads, no third-party analytics, no crash reporting, no telemetry. Most apps keep all data on the device; the few that use the network say exactly what for on the homepage transparency table.",
          "- The pages exist in English, German, Spanish, French, Japanese and Simplified Chinese (/de/, /es/, /fr/, /ja/, /zh-CN/)."]
    with open(os.path.join(ROOT, "llms.txt"), "w", encoding="utf-8") as f:
        f.write("\n".join(L).rstrip() + "\n")


def write_full(cat, post_items):
    L = ["# Blue Flame Games (BFG) — full reference", "",
         f"> {SUMMARY}", "",
         f"Last updated: {TODAY}. Short index: {SITE}/llms.txt. Machine-readable catalogue: {SITE}/apps.json", "",
         "## Company", "",
         "- Name: Blue Flame Games (short name BFG)",
         f"- Website: {SITE}/",
         "- App Store developer page: https://apps.apple.com/developer/blue-flame-games/id523824138",
         "- Contact: blueflamegames@proton.me",
         "- Platforms: iPhone and iPad; some apps also run on Mac and Apple Watch. No Android versions.",
         "- Website languages: English, German, Spanish, French, Japanese, Simplified Chinese.", "",
         "## Apps", ""]
    for a in cat:
        L += [f'### {a["name"]}', "", f'- Page: {a["url"]}', f'- App Store: {a["appStoreUrl"]}',
              f'- Platforms: {", ".join(a["platforms"])}', f'- Category: {a["category"]}',
              f'- Price: {a["priceModel"]}', f'- Privacy: {a["privacy"]}',
              f'- Privacy policy: {a["privacyUrl"]}; support: {a["supportUrl"]}', "",
              a["summary"], "", f'Who it is for: {a["audience"]}', ""]
        for q, ans in faq_of(f'apps/{a["slug"]}/index.html'):
            L += [f"**{q}**", "", ans, ""]
    L += ["## Coming soon", ""]
    for name, slug, desc in catalogue.COMING_SOON:
        L += [f"### {name}", "", f"- Page: {SITE}/apps/{slug}/", "- Status: coming soon (not yet on the App Store)", "", desc, ""]
        for q, ans in faq_of(f"apps/{slug}/index.html"):
            L += [f"**{q}**", "", ans, ""]
    L += ["## Blog articles", ""]
    for p in sorted(post_items, key=lambda p: p["published"], reverse=True):
        L += [f'### {p["title"]}', "", f'- URL: {p["url"]}', f'- Category: {p["category"]}',
              f'- Published: {p["published"]}; updated: {p["modified"]}', "", p["description"] or "", ""]
        for q, ans in p["faq"]:
            L += [f"**{q}**", "", ans, ""]
    with open(os.path.join(ROOT, "llms-full.txt"), "w", encoding="utf-8") as f:
        f.write("\n".join(L).rstrip() + "\n")


if __name__ == "__main__":
    p, cat = posts(), catalogue.catalogue()
    write_llms(p, cat)
    write_full(cat, p)
    write_catalogue_json(cat)
    print(f"llms.txt, llms-full.txt, apps.json: {len(cat)} apps, {len(p)} posts")
